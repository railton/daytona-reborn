#!/usr/bin/env python3
"""Compile the desktop home shaders with DXC (DXIL and SPIR-V)."""

import argparse
from pathlib import Path
import subprocess
from tempfile import TemporaryDirectory


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dxc", default="dxc")
    args = parser.parse_args()
    gpu = Path(__file__).resolve().parents[1] / "src/app/gpu"
    output = ["// Generated by scripts/build_home_shaders.py from home.hlsl.", "#pragma once", ""]
    with TemporaryDirectory() as work:
        binary = Path(work) / "home.shader"
        for entry in ("vs_home", "ps_home", "vs_lens", "ps_lens"):
            for kind, flags in (("spv", ["-spirv", "-fspv-entrypoint-name=main"]), ("dxil", [])):
                subprocess.run([args.dxc, *flags, "-Qstrip_debug", "-T", entry[:2] + "_6_0",
                                "-E", entry, "-Fo", str(binary), str(gpu / "home.hlsl")], check=True)
                data = binary.read_bytes()
                output.append(f"inline constexpr unsigned char k_{entry}_{kind}[] = {{")
                for start in range(0, len(data), 16):
                    output.append("    " + ", ".join(f"0x{b:02x}" for b in data[start:start + 16]) + ",")
                output.extend(("};", ""))
    (gpu / "home_shaders_gen.h").write_text("\n".join(output), encoding="utf-8")


if __name__ == "__main__":
    main()
