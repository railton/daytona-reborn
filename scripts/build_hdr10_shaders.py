#!/usr/bin/env python3
"""Compile the HDR10 compose shader with DXC.

DXIL is always written. SPIR-V arrays are added only when this DXC can emit
them. Direct3D 12 is the HDR10 target, so a DXIL-only header is valid.
"""

import argparse
from pathlib import Path
import subprocess
from tempfile import TemporaryDirectory


def compile_shader(dxc, flags, profile, entry, source, binary):
    result = subprocess.run(
        [dxc, *flags, "-Qstrip_debug", "-T", profile, "-E", entry,
         "-Fo", str(binary), str(source)],
        capture_output=True, text=True)
    if result.returncode != 0:
        if result.stdout:
            print(result.stdout, end="" if result.stdout.endswith("\n") else "\n")
        if result.stderr:
            print(result.stderr, end="" if result.stderr.endswith("\n") else "\n")
    return result.returncode == 0


def append_array(output, name, data):
    output.append(f"inline constexpr unsigned char {name}[] = {{")
    for start in range(0, len(data), 16):
        output.append("    " + ", ".join(f"0x{b:02x}" for b in data[start:start + 16]) + ",")
    output.extend(("};", ""))
    print(f"build_hdr10_shaders: {name} {len(data)} bytes")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dxc", default="dxc")
    args = parser.parse_args()
    gpu = Path(__file__).resolve().parents[1] / "src/app/gpu"
    source = gpu / "hdr10_compose.hlsl"
    output = ["// Generated by scripts/build_hdr10_shaders.py from hdr10_compose.hlsl.",
              "#pragma once", ""]
    entries = ("vs_hdr10", "ps_hdr10", "ps_sdr_curve")
    spirv_flags = ["-spirv", "-fspv-entrypoint-name=main"]
    with TemporaryDirectory() as work:
        binary = Path(work) / "hdr10.shader"
        spirv = compile_shader(args.dxc, spirv_flags, "vs_6_0", "vs_hdr10", source, binary)
        if spirv:
            print("build_hdr10_shaders: DXC emitted SPIR-V; header contains DXIL and SPIR-V")
        else:
            print("build_hdr10_shaders: DXC cannot emit SPIR-V; hdr10_shaders_gen.h contains DXIL only")
        for entry in entries:
            profile = entry[:2] + "_6_0"
            if spirv:
                if not compile_shader(args.dxc, spirv_flags, profile, entry, source, binary):
                    raise SystemExit(f"build_hdr10_shaders: SPIR-V failed for {entry}")
                append_array(output, f"k_{entry}_spv", binary.read_bytes())
            if not compile_shader(args.dxc, [], profile, entry, source, binary):
                raise SystemExit(f"build_hdr10_shaders: DXIL failed for {entry}")
            append_array(output, f"k_{entry}_dxil", binary.read_bytes())
    (gpu / "hdr10_shaders_gen.h").write_text("\n".join(output), encoding="utf-8")


if __name__ == "__main__":
    main()
